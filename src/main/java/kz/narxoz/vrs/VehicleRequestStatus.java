package kz.narxoz.vrs;

/**
 * Статусы, через которые проходит заявка на транспорт.
 */
public enum VehicleRequestStatus {

    /** Черновик: сотрудник ещё заполняет заявку. */
    DRAFT,

    /** Заявка отправлена руководителю на согласование. */
    SUBMITTED,

    /** Руководитель согласовал заявку. */
    APPROVED,

    /** Диспетчер назначил машину и водителя. */
    ASSIGNED,

    /** Поездка состоялась, заявка закрыта. */
    COMPLETED,

    /** Заявка отклонена. */
    REJECTED
}
